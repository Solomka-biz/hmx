Сейчас мы поговорим про ремаркетинг AdWords, а также о его фантастических преимуществах.            </p>

<h4>С чего начинаются наши действия</h4>
<p class="description">Во-первых, мы осуществляем переход по ссылке: <noindex><a href="https://adwords.google.com" target="_blank"  rel="nofollow">https://adwords.google.com</a></noindex> и  входим в свою учётную запись Google AdWords.<br />
В том случае если учётная запись ещё не создана, то необходимо её создать, щёлкнуть клавишу «Начать сейчас».
 </p>
 <img src="/images/adwords1.jpg" />
<p class="description">Во-вторых, мы указываем адрес электронной почты и другие данные, и только потом нажимаем клавишу, находящуюся слева, «Сохранить и продолжить».</p>
 <img src="/images/adwords2.jpg" />
<p class="description">В-третьих, сделаем переход в пункт «Кампании» и нажмём клавишу, которая находится слева: «Создать кампанию».</p>
 <img src="/images/adwords3.jpg" />
<p class="description">В том случае если вы когда-нибудь пользовались Google AdWords, тогда в подпункте «Настройки» нужно нажать клавишу красноватого цвета «+ Кампания».</p>
 <img src="/images/adwords4.jpg" />
<p class="description">В-четвёртых, в перечне, который выпадает выбрать раздел «Только контекстно-медийная сеть». Это значит, что объявление сможет передаваться в пределах сети сайтов компаньонов Google.</p>
 <img src="/images/adwords5.jpg" />
<p class="description"> В-пятых, вводим наименование кампании, затем выбираем свойство справа: «Нет маркетинговой цели».</p>
 <img src="/images/adwords6.jpg" />
<p class="description"> В-шестых, выбираем язык публики и определяем повседневный баланс в настройках, находящихся пониже. Есть возможность в балансе указывать различную стоимость, потому что наполнение группы ремаркетинга происходит медленно.</p>
 <img src="/images/adwords7.jpg" />
<p class="description">В-седьмых, если есть желание, то можно осуществить настройку дополнительных параметров. Когда все настройки подрегулированы, нужно кнопку нажать «Сохранить и продолжить», которая расположена внизу. </p>
 <img src="/images/adwords8.jpg" />
<p class="description">В-восьмых, при переходе на последующую страничку нажимаем клавишу «Пропустить создание группы объявлений». </p>
 <img src="/images/adwords9.jpg" />
<p class="description"> В-девятых, слева на страничке, которая называется управления кампаниями, выбираем раздел «Общая библиотека». Затем щёлкаем пункт «Аудитории», затем нажимаем клавишу «Настроить ремаркетинг». </p>
 <img src="/images/adwords10.jpg" />
<p class="description">В-десятых, для просмотра тег ремаркетинга AdWords стоит нажать на необходимую ссылку.  </p>
 <img src="/images/adwords11.jpg" />
<p class="description">Одиннадцатое, когда область с кодировкой ремаркетинга раскроется, надо из этого места скопировать принятую кодировку.  </p>
 <img src="/images/adwords12.jpg" />
<p class="description"> Двенадцатое, открываем в визуальном редакторе LPgenerator посадочную страницу, с помощью неё можно будет искать пользователей. Главная страничка, потому как Google даёт возможность включать этот инструмент в том случае, когда количество в группе достигнет не меньше ста пользователей. </p>
<p class="description"> Тринадцатое, нажимаем инструмент «Скрипты»: </p>

<ul>
<li>щёлкните «Добавить скрипт»;</li>
<li>дайте ему название;</li>
<li>установите необходимое положение скрипта: перед тегом;</li>
<li>вводим кодирование ремаркетинга для Google AdWords, который скопировали ранее, и сохраняем страничку.</li>
</ul>

<p class="description"> Четырнадцатое, возвратитесь в Google AdWords, необходимо снять отметку с пункта «Отправить инструкции по электронной почте», жмём клавишу «Продолжить». А затем опять возвращаемся в окно с настройками кампании. </p>
<img src="/images/adwords13.jpg" />

<p class="description">Пятнадцатое, затем на страничке выбираем «Все интернет-кампании», затем производим выбор своей кампании и нажимаем «+ группа объявлений».  </p>
<img src="/images/adwords14.jpg" />
<p class="description"> Шестнадцатое, определяем сумму (рекомендуется установить цену в рамках 10–15 рублей). Выбираем метод «Интересы и ремаркетинг». Производим нажатие на стрелочки, чтобы перечни ремаркетинга AdWords активировались, и выбираем необходимый. Нужный список возникнет в столбике справа. </p>
<img src="/images/adwords15.jpg" />
<p class="description">Семнадцатое, нажимаем клавишу «Сохранить и продолжить». <br />
<img src="/images/adwords16.jpg" /><br />
Чуть ниже раскроется окно для формирования медийного объявления с областями заполнения.

Заглавие объявления необходимо сделать таким, чтобы создавалось впечатление, что вы ранее встречались с посетителем, потому как многие уже посещали наш веб-сайт.
Также в поле «Описание» указать достоинства услуги. А в поле «Отображаемый URL» ввести адрес посадочной страницы.
Также стоит сделать акцент на поле «Целевой URL», в котором можно добавить ссылку с UTM отметками, с целью прослеживать увеличенную статистику по всем переходам.</p>
<img src="/images/adwords17.jpg" />
  

