            <p class="description">Ремаркетинг Google AdWords делает возможным сбор публики с целью просмотра созданной вами рекламы на различных сайтах-партнёрах AdSense. Чтобы увеличить максимальный эффект, нужно не дать возможности пользователям веб-сайта забыть о вашем существование, когда закладки будут закрыты. </p>

