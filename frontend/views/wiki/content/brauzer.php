            операционной системой Windows, которая уже тогда завоевала почти 90% рынка. Именно столько пользователей и
            выбрало данный браузер. </p>

        <p class="description"><br/>
            Впрочем, даже после окончания войны браузеры от разных разработчиков продолжают конкурировать между собой.
