            выглядеть по разному, что уж говорить о браузере текстовом или мобильном? Это обстоятельство при верстке
            сайта обязательно учитывают. В противном случае юзабилити может серьезно пострадать. </p>

        <p class="description"><br/>
            Браузер – программы, которые устанавливаются непосредственно на компьютерах пользователей, поэтому они никак
            не влияют на поисковую <a href="<?= \Yii::link()->site() ?>">раскрутку сайта</a>. Однако учитывать то, что
