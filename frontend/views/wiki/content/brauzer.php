        <p class="description">
            Попробуем выделить основные:<br/>
            1) Браузер командной строки. Это наиболее «древний» обозреватель, которым пользовались
            лишь единицы – первые пользователи и разработчики Интернета. Он позволял загружать на
            компьютер какие-либо файлы после того, как в командную строку вводили адрес (как
            правило, <a href="<?= \Yii::link()->wiki('url') ?>">урл (url)</a> представлял из себя IP-адрес). </p>

        <p class="description"><br/>
            2) Текстовый браузер. Сегодня это не настолько популярный вид, но им все же пользуются. Тем более, что
            работают такие программы, как правило, быстрее и эффективнее. Особенность таких программ – возможность
            загружать лишь текст, без мультимедиа.</p>

        <p class="description"><br/>
            3) Мультимедийные браузеры (IE, Mozilla Firefox и т.д.) – программы, загружающие как текст, так и все
