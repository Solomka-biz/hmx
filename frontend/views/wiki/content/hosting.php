        <p class="description"><br/>
            - Виртуальный хостинг. Это наиболее доступная услуга, которая иногда предоставляется и вовсе бесплатно.
            Заказывая ее, Вы получаете место на диске, где наверняка уже расположены сайты нескольких десятков или сотен
            пользователей. В некоторых случаях (у самых «демократичных» провайдеров) нет даже разграничения прав, и к
            вашему сайту может получить доступ любой из тех, чьи сайты размещены на том же диске.</p>

        <p class="description"><br/>
            - Выделенный хостинг. Это аренда целого <a href="/server.html">сервера</a>. На нем можно разместить особо
            «тяжелый» проект или сервис, требующий высокую пропускную способность и много физической памяти. Пользуются
            таким хостингом и те, кто владеет целыми сетками сайтов (дорвеев, сателлитов, используемых для раскрутки
            сайтов).</p>

        <p class="description"><br/>
            - Виртуальный выделенный хостинг. Пользователь имеет все те же преимущества, что и в предыдущем случае,
