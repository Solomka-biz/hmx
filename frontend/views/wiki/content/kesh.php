        <p class="description"><br/>
            В случае, если пользователь повторно обращается к файлу, он вводит адрес (либо нажимает на соответствующую
            ссылку или ярлык). Запрос компьютером отсылается в первую очередь к кэшу. В кэше проверяется, есть ли в нем
            такой идентификатор (т.е. адрес файла). Если он есть, кэш ищет в своей памяти элементы данных, т.е. сам
            контент этого файла. Если элементы были найдены, файл загружается.</p>

        <p class="description"><br/>
            Несмотря на то, что со стороны все это может показаться сложным, кэш работает гораздо быстрее. Дело в том,
