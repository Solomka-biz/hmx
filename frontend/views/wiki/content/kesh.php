            <a href="/контент.html">контент</a>. В случае с веб-страницей
            адресом ее будет тот адрес, что Вы видите в адресной строке, а содержимом (элементами данных) –
            непосредственно контент, включая текст, картинки и т.д. И то, и другое сохраняется в кэше в случае, если эту
            страницу открывает пользователь. То же можно сказать и о любом другом файле, размещенном на компьютере,
