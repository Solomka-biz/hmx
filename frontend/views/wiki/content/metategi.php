        <p class="description">
            Мета-теги являются HTML тегами, они указывают поисковым системам краткое описание содержания документа.
            Особого внимания заслуживают метатеги Title и Description. </p>

        <p class="description"> Title определяет заголовок, а Description содержимое каждой HTML-страницы. Сначала
                                Description использовали поисковики, как <a href="сниппет.html">сниппет</a>, то есть
                                текст, расположенный под заголовком страницы в выдаче. Но в настоящее время сниппеты
                                формируются интеллектуально, то есть из текста всей страницы выбирают часть, которая
                                самая релевантная по запросам пользователей.Именно она будет сниппетом. </p>

        <p class="description">Но зачастую бывает, что сниппет для страницы формируется и из текста, который расположен
                               в мета-теге description. Поэтому важно правильно его заполнить и обратить на него свое
                               пристальное внимание.
                               А заполняется он таким образом:
            <br/>
                               [<i>META name=”description” content=” Детские игрушки, куклы и пупсы отечественного
                                   производителя, вы сможете выбрать недорогие игрушки..” </i>] </p>

        <p class="description">Описание может быть любой длины, но в выдаче будет только часть текста, поэтому основные
                               ключевые фразы надо располагать в самом начале. </p>

        <p class="description">Keywords тоже располагается внутри тега head в HTML-документах. Прописывают мета-теги
                               этого вида таким образом: <br/>
                               [<i>META name=”keywords” content=”детские игрушки, куклы от производителя в Москве,
                                   велосипеды</i>”] </p>

        <p class="description">Не нужно прописывать одну и ту же фразу или ключевик очень часто.

                               И обязательно нужно делать отдельные мета-теги для каждой страницы.</p>
