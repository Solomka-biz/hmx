        <p class="description"><br/>
            - Вынесение предупреждений и применение других санкций к участникам, вплоть до
            <a href="/бан">бана</a>;</p>

        <p class="description"><br/>
            - Разрешение конфликтов между пользователями.</p>

        <p class="description"><br/>
            Модератор может работать как с одной частью ресурса (например, подфорумом), так и с целым ресурсов. Все
            зависит от объема работы. Не нуждаются в модерации сервисы блогов, ICQ и другие подобные сети, Википедия и
            ее аналоги. В одних случаях функции модератора выполняют сами участники – например, владелец блога, в других
            – администраторы. Контроль, модерация сообщений и действий участников необходима в любом случае, даже если
