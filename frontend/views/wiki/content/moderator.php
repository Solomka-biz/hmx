    <div class="right_articles">
        <h3>Типы модерации.</h3>

        <p class="description">
            Модерация может проводиться различными способами. Сегодня можно выделить три типа модерации:</p>

        <p class="description"><br/>
            1) Премодерация<br/>
            Модерация этого вида осуществляется непосредственно перед тем, как контент, добавленный пользователем, будет
            опубликован. Сообщение проверяют на соответствие правил, иногда и на плагиат, в нем могут исправляться
            ошибки и опечатки, после чего модератор публикует его на сайте. Либо не публикует, если это спам или просто
            сообщение, не соответствующее принятым нормам. Модерация этого типа активно используется на сайтах с
            небольшим количеством пользователей, либо на сайтах, где не нужно публиковать сообщения мгновенно. Главными
            недостатками премодерации являются отсутствие онлайн-составляющей (участники не могут общаться между собой в
            режиме реального времени) и большой объем работы у модератора. Однако только с помощью такой модерации в
            процессе <a href="<?= \Yii::link()->site() ?>">раскрутки сайта</a> можно добиться идеальной чистоты ресурса от различного сетевого
            мусора.</p>

        <p class="description"><br/>
            2) Постомодерация<br/>
            В данном случае сообщение проверяется уже после его публикации. Это единственный вид модерации, возможный на
            форумах и в чатах. Однако при этом ресурс довольно быстро может заполниться спамом, флудом и другими
            подобными явлениями в отсутствие модератора. </p>

        <p class="description"><br/>
            3) Автомодерация <br/>
            Модерация данного вида проходит в автоматическом режиме, для чего используются специальные программные
            модули. Так, от спама довольно легко избавиться, установив <a href="/captcha.html">капчу</a> перед
            публикацией сообщения. А от вредоносных или просто ненужных сообщений можно избавиться путем ввода
            голосования самих участников. При автомодерации возможны &quot;накрутки&quot; и обман со стороны участников,
            поэтому модераторы все же набираются.</p>
