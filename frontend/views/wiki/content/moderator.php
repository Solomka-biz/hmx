        <h3>Функции модератора.</h3>

        <p class="description">
            В сети Интернет функционирует огромное количество ресурсов, где каждый может высказать свое мнение, обсудить
            определенную проблему или просто пообщаться в кругу единомышленников. Такие ресурсы имеют четкие правила,
            регламентирующие поведение участников. К сожалению, некоторые посетители не считают нужным ознакомиться с
            правилами. Такие персонажи позволяют себе общение в манере, оскорбительной для других участников. К
            недопустимому поведению относятся также троллинг и распространение спама на публичных Интернет площадках для
            тематического общения. </p>

        <p class="description"><br/>
            Основных функций модератора не так уж много – в его обязанности входит просмотр
            <a href="/контент.html">контента</a> на предмет нецензурной брани,
            оскорбительных высказываний, перехода на личности, оффтопика, спама, троллинга и прочего недопустимого
            поведения. В этих случаях модератор может применить санкции против нарушителя (просьба, предупреждение или
            бан), а саму запись или топик отредактировать или удалить.</p>

        <p class="description"><br/>
            Бан обычно носит временный характер и ограничивает возможность создавать новые обсуждения, комментировать, а
            в некоторых случаях – отправлять личные сообщения. Злостных нарушителей модератор имеет право забанить
            навсегда.</p>

        <p class="description"><br/>
            Помимо санкций нарушителям, у модератора есть полномочия создавать прикрепленные темы, а также отделять
            ветви дискуссии, если обсуждение далеко отклонилось от первоначальной темы, закрывать и даже удалять
            отдельные ветки дискуссии, если обсуждение зашло в тупик.</p>
