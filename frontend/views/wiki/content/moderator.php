            усмотрение. Самый типичный пример – это форумы и чаты, а также всевозможные интернет-конференции, где
            большинство пользователей уравнены в правах. Только модераторы имеют чуть больше прав и обязанностей.</p>

        <p class="description"><br/>
            В обязанности модератора входит:</p>

        <p class="description"><br/>
            - Чтение сообщений пользователей и выявление нарушений правил;</p>

        <p class="description"><br/>
            - Устранение нарушений (например, модераторы стирают спам и <a href="/plagiat.html">плагиат</a>, если
