            Почему же не все «продажные» ссылки подпадают под непот-фильтр? И можно ли его обойти?</p>

        <p class="description"><br/>
            Поисковые системы и их алгоритмы далеко не идеальны. Да и сами seo-специалисты придумывают все более
            изощренные пути обхода алгоритмов, поэтому с почти 100%-ной эффективностью непот-фильтр действовал лишь
            несколько месяцев. После этого специалисты уже разработали ряд правил, позволяющих обойти этот фильтр, и
            выявили несколько факторов, влекущих за собой санкции с его стороны:</p>

        <p class="description"><br/>
            - Нетематичность ссылок (фильтр учитывает тематику страницы-донора, страницы, куда ведет ссылка, и текста
            самой ссылки);</p>

        <p class="description"><br/>
            - Неестественность ссылок на разных ресурсах, ведущих на один сайт (так, появление сразу большого количества
            внешних ссылок или использование доноров одного типа и с одними и теми же показателями);</p>

        <p class="description"><br/>
