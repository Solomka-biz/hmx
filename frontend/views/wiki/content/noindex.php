 <h4> Для чего используется NOINDEX</h4>

        <p class="description">
Предназначение тэга – показать поисковым системам места на веб страницах, которые не следует <a href="/indeks.html">индексировать</a>. Для исключения индексации эти места должны быть помещены внутри открывающего и закрывающего тега. Так Яндекс рекомендует скрывать некоторые участки текста.<br />

Ссылки этим тегом не скрываются. Если между NOINDEX разместить ссылку, то не будет учтен только её анкор, а сама ссылка проиндексируется. </p>

 <h4>Размещение NOINDEX</h4>
        <p class="description">
Размещать этот тег можно в любом месте кода html-страницы, сколько угодно раз. Например, если структура текста на определенной странице предполагает, что в нескольких местах будет размещаться одинаковый текст, то дубли заключают в noindex.<br />

Если нужно закрыть от поисковых систем всю страницу, то NOINDEX размещают непосредственно в мета-теге ROBOTS, отвечающем за всю страницу.  

