        <h3>Зачем нужна оптимизация сайта?</h3>

        <p class="description">
            Многие компании сегодня имеют сайты, на которых они всем рассказывают о своей деятельности. Но часто,
            заказав, а затем, выложив в Интернет сайт, компании в нем разочаровываются. Почему это происходит? </p>

        <p class="description">
            Потому, что на сайт заходит мало посетителей и в компанию никто не обращается, чтобы купить
            продукцию или заказать услугу.
            Чтобы на сайт заходили посетители, нужно, чтобы они его могли найти. 
            Сайт должен в <a href="/vidacha.html" title="поисковая выдача">выдаче
            поисковой системы</a> находиться не дальше, чем на третьей странице. В идеале он должен быть
            на первой странице выдачи – в топ 3. И чтобы достичь такой видимости, сайту необходима
            оптимизация. </p>

        <p class="description">
            Оптимизация сайта это целая наука. Чтобы сайт можно было найти в сети по нужным ключевым
            словам необходимо написать для него тексты, заточенные под ключевики, тщательно
            проанализировать каждую его страницу, грамотно перелинковать страницы между собой. </p>
            
