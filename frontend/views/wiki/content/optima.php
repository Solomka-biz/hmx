        <h4>Стоит ли оптимизировать сайт самому?</h4>

        <p class="description">
            Самостоятельно можно использовать самые простые методы оптимизации, понимя, что при определении рейтинга сайта, 
            поисковые системы используют две принципиально различные системы оценки. </p>

        <ul class="wikiul">
        <li>Во-первых, оценивается число и качество цитирующих анализируемый сайт ссылок на других
                                ресурсах. </li>

        <li>Во-вторых, сопоставляется внутреннее содержание веб-сайта. </li>
        </ul>

        <p class="description">Оптимизация сайта служит задаче повышения его привлекательности для поисковиков. Принципы
                               работы поисковых машин во многом сходны, но детали могут позволить "привязать" сайт к
                               конкретному поисковику. </p>

        <p class="description">
            Для самостоятельной оптимизации сайта следует помнить ряд нюансов:
            <ul class="wikiul">
            <li>размещенные тексты должны быть специализированы под запросы поисковиков. В них должны
            быть ключевые слова или словосочетания, которые целенаправленно продвигаются в поисковых
            системах. Целесообразно будет поместить ключи в состав заголовков и подзаголовков.
            Примерная плотность их в основной части должна быть в рамках 2-7%.</li>
            <li>оптимизация дизайна сайта должна учитывать возможности поисковиков. Нежелательно
            оформлять ключевой текст в виде элементов флеш или картинок.</li>
            <li>для занятия топовых позиций в списке поиска, необходимо соответственно спроектировать
            структуру сайта и названия его разделов. Путь от главной страницы до любой информации
            должен занимать не больше трех кликов мышкой, это позволит поисковым роботам эффективно
            поддерживать актуальную индексацию страниц. Для объемных сайтов полезно создать карту
            ссылок.</li>
            </ul>
