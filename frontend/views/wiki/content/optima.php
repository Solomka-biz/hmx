            проводить семантический анализ текста – с целью отсеивания поискового спама, когда
            плотность ключевых слов слишком высокая.</li>
            <br/>
            <li>Индекс цитирования сайта, который зависит от авторитетности и
            количества ссылающихся на этот сайт веб-ресурсов. Иногда важно, чтоб ссылки были с сайтов
            тематики, аналогичной тематике оптимизируемого сайта. </li>
            <br/>
            <li>Поведенческие факторы сайта, которые складываются от того, как себя ведут пользователи на сайте. 
            Сколько времени проводят на странице, сколько страниц просматривают итп.</li>
