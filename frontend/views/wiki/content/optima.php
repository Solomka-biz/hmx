        <h4>Какая бывает оптимизация сайта (черная, белая, серая)?</h4>

        <p class="description"> На сегодняшний день различают три вида оптимизации – белую, серую и чёрную. </p>

        <p class="description">Белой оптимизацией называется оптимизаторский труд над тем или иным ресурсом без
                               использования методов наскрутки, официально запрещённых всеми поисковыми системами – без
                               воздействия на поисковые алгоритмы интернет-сайтов. </p>

        <p class="description">Это означает как работу над самим интернет-сайтом, а конкретно над его <a href="/контент.html" title="содержимое контент сайта">содержимым</a> и
                               внутренней навигацией, так и работу с наружной средой сайта – т.е. продвижением сайта с
                               помощью пресс-релизов, партнёрских программ, регистрации в различных социальных закладках
                               и пр., но с указанием ссылок на оптимизируемый сайт. </p>

        <p class="description">Заметим, что Яндекс уведомляет о том факте, что если тот или иной метод оптимизации
                               официально не запрещён, то это ещё не означает, что его разрешено использовать. </p>

        <p class="description">Наиболее распространённым видом серой поисковой оптимизации считается метод добавления
                               солидного количества ключевых слов или словосочетаний в текст страницы, нередко в ущерб
                               читабельности для посетителей сайта. Серая оптимизация, в отличие от чёрной, официально
                               не запрещена, но её употребление могут расценить как неестественное повышение
                               популярности сайта. </p>

        <p class="description">Отдельные поисковые системы – Google к примеру, могут заблокировать подобный сайт. Но
                               окончательное решение о законности методов продвижения принимает не автоматика, а
                               человек-эксперт. </p>

        <p class="description">Ну а «чёрная» оптимизация – это употребление <a href="/dorvei.html" title="запрещенные дорвеи">дорвеев</a>, <a href="/cloaking.html" title="клоакинг">клоакинга</a>, однопиксельных ссылок, а
                               также скрытого текста на страничках ресурса. </p>
