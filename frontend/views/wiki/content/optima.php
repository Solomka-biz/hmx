            Соответственно результатом качественной оптимизации является получение самых 
            высоких позиций сайта в поисковых системах.
            Когда анализируется эффективность поисковой оптимизации, принимается в расчёт 
            стоимость целевого посетителя, при учете затрат на оптимизацию и количества посетителей. </p>
            

        <p class="description">
