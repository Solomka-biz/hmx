        <p class="description">
            Всем известно, что положение отдельно взятой страницы в выдачах поисковых систем напрямую зависит от того,
            какое количество страниц на нее ссылается. Однако основное внимание уделяют внешним ссылкам, незаслуженно
            забыв о внутренних.

            Для чего нужна внутренняя перелинковка?

            <br/>
            1. Внутренняя перелинковка улучшает навигацию сайта или блога. Если внутренняя ссылка стоит в нужном месте,
            она заставляет посетителя перейти на предлагаемую страницу, где он сможет прочитать и изучить дополнительную
            информацию.
            <br/>
            2. Повышается индексация блога или сайта роботами поисковых систем, ведь известно, что они охотнее переходят
            по ссылкам, исходящим не из меню, а непосредственно из текста.<br/>
            3. Внутренняя перелинковка помогает в <a href="/">поисковом продвижении</a> ресурса
            – при правильной расстановке внутренних ссылок на конкретный текст, вполне возможно попасть в топ поисковых
            систем, не используя внешние ссылки на блог или сайт.
            <br/>
            4. Размещение внутренних ссылок способствует увеличению PR страниц блога или сайта – чем большее количество
            страниц ссылается на главную страницу ресурса, тем выше поднимается ее авторитет и тем больше можно на нем
            заработать. </p>

        <p class="description">Внутренняя перелинковка абсолютно безопасна и не отражается на имидже сайта негативно –
                               поисковые системы относятся к данному явлению вполне дружелюбно. Единственный минус
                               внутренних ссылок – это необходимость ставить их в тексты самостоятельно, не прибегая к
                               помощи автоматизации процесса.</p>
