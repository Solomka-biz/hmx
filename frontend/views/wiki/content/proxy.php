    <div class="right_articles">
        <h3>Виды прокси.</h3>

        <p class="description">
            Существует достаточно много разновидностей прокси. Некоторые из них мы рассмотрим здесь.</p>

        <p class="description"><br/>
            - HTTP прокси. Это одна из самых распространенных разновидностей. Прокси использует протокол http. Если Вы
            используется программу, где не прописан тип прокси, скорее всего, это HTTP. Существует и разновидность –
            HTTPS прокси, который шифрует данные и по протоколу SSL.</p>

        <p class="description"><br/>
            - NAT прокси – прозрачный прокси-сервер, предустановленный в операционных системах Windows 2000, XP и другие
            ОС Windows выше 2000. Включить его совсем несложно – достаточно зайти в «Свойства соединения» и поставить
            галочку в соответствующей строке. В дополнительной настройке он не нуждается.</p>

        <p class="description"><br/>
            - CGI proxy. Еще одно название – анонимайзер. Является скриптом на веб-сервере, а не какой-то отдельной
            службе, поэтому им можно пользоваться только в <a href="/brauzer.html">браузере</a>. Прокси этого вида можно
            использовать для запрещения показа картинок или рекламы, а также для получения анонимности.</p>

        <p class="description"><br/>
            - IRC proxy. Данный вид используют для получения доступа в IRC (файлообменную) сеть с анонимным IP.</p>

        <p class="description"><br/>
            Кроме перечисленных выше, существуют такие виды прокси, как SOCKS, FTP, MySQL proxy, но используются они
            гораздо реже. </p>

        <p class="description"><br/>
            Далеко не все виды прокси поддерживают анонимность. Так, прозрачный NAT прокси не скрывает ни собственного
            присутствия, ни IP-адреса клиента. Другие разновидности могут скрыть или заменить IP-адрес пользователя, не
            скрывая своего присутствия. Прокси-сервера с высоким уровнем анонимности скрывают и сам факт своего
            присутствия, заменяя IP-адрес пользователя на другой.</p>
