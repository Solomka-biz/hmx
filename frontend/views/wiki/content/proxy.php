            которая может быть установлена на любом компьютере. Существует достаточно много таких программ, которые
            подходят сразу для нескольких операционных систем и браузеров. </p>

        <p class="description"><br/>
            Еще одна особенность прокси-сервера, ради которой чаще всего и устанавливают эту программу, в том числе и в
            процессе <a href="<?= \Yii::link()->site() ?>">раскрутки сайта</a> - это наличие собственного IP-адреса. Каждый компьютер (а точнее,
            точка соединения с Интернетом) имеет свой IP-адрес и при соединении к тому или иному ресурсу этот адрес
