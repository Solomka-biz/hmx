        <h3>Основные функции прокси.</h3>

        <p class="description">
            Прокси-сервер чаще всего используется в локальных сетях, обеспечивая им доступ в Интернет. Однако на этом
            функции программы не ограничиваются:</p>

        <p class="description"><br/>
            1) Обеспечение анонимности. При подключении к Интернету через прокси пользователь «получает» новый IP-адрес
            – адрес прокси-сервера, что позволяет ему выходить в сеть анонимно. При прямом подключении анонимность
            невозможна: компьютер сообщает сторонним ресурсам свой IP-адрес, по которому можно определить и физический
            адрес. </p>

        <p class="description"><br/>
            2) Получение доступа на некоторые ресурсы. Некоторые ресурсы ограничивают доступ для пользователей
            определенного вида. Типичный пример – бан для участника форума или чата, а также ограничение для
            представителей какой-либо страны. Для того, чтобы попасть на ресурс, необходимо подключиться к
            прокси-серверу. </p>

        <p class="description"><br/>
            3) Управление доступом в Интернет компьютеров, входящих в локальную сеть. С помощью прокси-сервера можно
            закрыть для пользователей определенные сайты (для корпоративных локальных сетей это особенно актуально), а
            также защитить саму сеть от обращения со стороны внешних компьютеров. Последние будут «видеть» только
            прокси-сервер.</p>

        <p class="description"><br/>
            4) Ускорение подключения к сети. С помощью прокси можно кэшировать данные с часто посещаемых ресурсов, а
            также сжимать скачиваемый <a href="/контент.html">контент</a>.
            Благодаря этому снижается нагрузка на канал и уменьшается потребление трафика.</p>
