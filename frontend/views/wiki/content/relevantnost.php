        <h4>Как повысить релевантность сайта?</h4>

        <p class="description">
            Релевантность необходима чтобы определять эффективность работы поисковых систем. Она показывает степень
            соответствия выбранного документа или страницы интернета запросу пользователя. То, есть, документ будет
            релевантным, если он соответствует сути запроса, сделанного через поисковик.</p>

        <p class="description">Повысить релевантность можно прописывая на каждой странице сайта ключевые слова, чтобы
