                               Некоторые поисковые системы показывают описание страницы из первых строчек документа, а
                               некоторые из тега Description. Составлять описание нужно таким образом, чтобы
                               пользователь захотел зайти на сайт. </p>

        <p class="description">Повысить релевантность поможет и использование на каждой странице большого количества
