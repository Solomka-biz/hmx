            продвижение и т.д.</p>

        <p class="description"><br/>
            3) Сбор данных для рекламодателей. Открытый счетчик-картинка позволяет проверить посещаемость сайта перед
            тем, как покупать на нем рекламу. Многие системы покупки-продажи мест под рекламу требуют установку такого
            счетчика на главной странице.</p>

        <p class="description"><br/>
