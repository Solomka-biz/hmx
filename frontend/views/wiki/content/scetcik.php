        </p>

        <p class="description"><br/>
            Счетчик состоит из специального скрипта, который устанавливается на сайт, и программы (движка) на основном
            ресурсе. Скрипт действует как поисковый робот, собирая информацию не о самом сайте, а о его посетителях, и
