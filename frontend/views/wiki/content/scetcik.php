    <div class="right_articles">
        <h3>Виды счетчиков.</h3>

        <p class="description">
            Существует несколько разновидностей счетчиков, каждый из которых имеет свои особенности.</p>

        <p class="description"><br/>
            - Счетчик-картинка. Это открытый для посетителей счетчик, в котором, как правило, отображается количество
            посетителей и посещений за определенный период (день, неделю, месяц, все время существования сайта).
            Преимущество таких счетчиков – это доступность основной информации для всех посетителей. Среди недостатков
            можно отметить тот факт, что такой счетчик учитывает лишь тех пользователей, которые загружают картинку.
            Пользователей, которые запретили загрузку картинок в браузере, а также поисковых роботов они не считают и не
            «видят».</p>

        <p class="description"><br/>
            - Счетчик в виде программного кода. Код на основе PHP выделяется в отдельный файл или размещается
            непосредственно на сайте. Наиболее часто он применяется на сайтах с динамическими адресами страниц. Счетчик
            подсчитывает всех пользователей, которые этого даже не замечают, так как он никак визуально на сайте не
            отображается. Это достаточно удобно для владельцев молодых сайтов, а также для всех тех, кто не нуждается в
            рекламодателях. К сожалению, такие счетчики нередко путают уникальных посетителей с неуникальными и
            наоборот.</p>

        <p class="description"><br/>
            - Комбинированный счетчик, включающий в себя и код, и картинку. Работают обе технологии: код собирает
            информацию из динамического окружения, а картинка – при загрузке страницы. И тот, и другой источник
            отправляет информацию в базу данных, где она обрабатывается. Может быть использована и невидимая глазу
            пользователя картинка.</p>
