            «человекообразном» виде: вместо IP-адреса или наряду с ним счетчик предоставляет информацию о
            местонахождении (страна, регион, город) пользователя, его возрасте и поле. Вместо адресов страниц поисковых
            систем – <a href="/keys.html">ключевые слова</a>, которые использовал посетитель.</p>

        <p class="description"><br/>
            Счетчик позволяет решать следующие задачи:</p>

        <p class="description"><br/>
            1) Сбор статистики для более эффективного продвижения сайта. Сео-специалисты, устанавливая счетчик на сайт,
            получают всю необходимую информацию, которую потом используют для коррекции продвижения и дооптимизации по
            наиболее популярным или, наоборот, не популярным на данный момент запросам.</p>

        <p class="description"><br/>
            2) Получение информации для демографического и географического <a href="/targeting.html">таргетинга</a>,
