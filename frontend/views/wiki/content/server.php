        <h3>Разновидности серверов.</h3>

        <p class="description">
            В зависимости от функций, которые выполняет сервер, он может принадлежать к одному из нескольких видов:<br/>
            - Web-сервер. Это довольно распространенный вид в Интернете, который предназначен для содержания и
            обеспечения доступа к web-ресурсам.</p>

        <p class="description"><br/>
            - Файловый сервер. Главное его назначение – хранение данных и распределение доступа к файлам. Критерии
            качества такого сервера – это объем дисковой памяти и степень защиты данных.</p>

        <p class="description"><br/>
            - Сервер баз данных. Является вспомогательной частью системы управления базы данных (СУБД). Такой сервер
            должен обеспечивать требующуюся пропускную способность и непрерывность работы.</p>

        <p class="description"><br/>
            - Коммуникационный сервер. Может выполнять роль прокси-сервера, маршрутизатора, распределителя IP-адресов,
            сервера для VPN (виртуальной приватной сети). Обеспечивает высокую защиту данных, анонимность в сети.</p>

        <p class="description"><br/>
            - Почтовый сервер. Как видно из названия, используется он для работы с электронной почтой – отправки и
            получения, обработки, хранения писем пользователей, <a href="/zelevie_posetiteli.html">целевых
                                                                                                   посетителей</a>. Чем
            больше локальная сеть, чем больше пользователей, тем важнее роль этого сервера.</p>

        <p class="description"><br/>
            - Сервер резервного копирования. Достаточно важная часть аппаратно-программного комплекса в любой компании.
            На этот сервер в автоматическом режиме копируется вся важная информация. В целях защиты информации от
            физической угрозы (например, пожара) он может располагаться в другом помещении или здании.</p>
