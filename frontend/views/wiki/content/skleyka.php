        <h4>
            Чем грозит склейка доменов?
        </h4>

        <p class="description">
            Для того чтобы все «показатели качества» переместились со старого на новый домен, и именно он показывался на
            нужных позициях в поисковиках, и получил ТИЦ и PR, накопленные старым доменом, применяется склейка доменов.
            Существует несколько способов, чтобы ее осуществить. </p>

        <p class="description">Можно использовать код ответа сервера 301 или 302 (так называемые 301-й и 302-й
                               редирект), а также директиву Host.
                               Получив код 301 («страница перемещена»), браузер меняет автоматически старый адрес на
                               новый, и открывает по нему страницу. Но есть один подвох - временной разрыв между
                               удалением старого домена из индекса поисковика и добавлением нового.
                               Команда «исключить страницу по старому адресу» выполняется моментально, а для команды
                               «добавить страницу по новому адресу» могут потребоваться дни, недели, а может и месяцы
                               (зависит от загрузки поискового робота). </p>

        <p class="description">Следовательно, в течение такого времени ваш сайт не будет показываться в поисковых
                               машинах. К тому же, поисковый робот может первую команду отработать для всех страница
                               сайта, тогда как вторую - только для некоторых, и часть сайта выпадет из индекса
                               совсем. </p>
                               
         <blockquote class="wikizitata">
