        <h4>Как избежать склейки доменов?</h4>

        <p class="description">
            Склейка доменов представляет собой процесс передачи основных параметров одного домена другому. Чаще всего
            этот процесс выполняется при переносе сайта в другую доменную зону, при полном переносе содержания. </p>

        <p class="description">Поисковики распознают "зеркала" и оставляют только лишь одно доменное имя в выдаче.
                               Зеркалами считаются сайты, которые являются полными либо частичными копиями. Копии могут
                               определяться роботом-поисковиком по совпадению содержимого на страницах с одинаковыми web
                               адресами. Также сайты являются зеркалами, если со страниц одного из сайтов настроена <a href="pereadresaziya.html" title="переадресация"> переадресация</a> на соответствующие страницы второго сайта. </p>
                
                <img src="images/bonding.png" class="wikizimg" alt="Склейка доменов зеркал">
            <p class="wikiunderimg">рис: Склейка зеркал необходима для правильной индексации</p>

        <p class="description">Робот-склейщик склеивает зеркала, а затем из них индексируется и, следовательно,
                               участвует в поиске лишь один из сайтов, тот, который является главным зеркалом.
                               Как же избежать нежелательной склейки доменов или добиться того, что после склеивания Ваш
                               сайт оставался главным зеркалом? </p>

        <p class="description">В общем случае робот-склейщик выбирает главное зеркало согласно своего алгоритма. В
                               Яндексе, например, обычно робот пользуется простым методом - чем короче будет домен, тем
                               лучше. Поэтому, осуществляя выбор между доменами с дефисом или без, робот Яндекса
                               остановится на последнем. Но роботу можно указывать на сайт, который ему нужно считать
                               главным. </p>

        <p class="description">Для этого используется директива Host. Директива Host не дает гарантии выбора указанного
                               главного зеркала, но тем не менее, робот-склейщик при принятии решения будет учитывать ее
                               с очень высоким приоритетом.</p>
                               
