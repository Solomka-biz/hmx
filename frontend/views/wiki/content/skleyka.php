         <h2>Зеркалами считаются сайты, которые являются полными либо частичными копиями.</h2> 
         </blockquote>


        <p class="description">Иногда используется склейка доменов через 302-й редирект, который полностью аналогичен
                               301-му, но говорит, что страница на новый адрес перемещена временно, а не насовсем.
                               Проблема в том, что поисковые системы не совсем знают, как обрабатывать 302
                               редирект. </p>

        <p class="description">Также, иногда меняют адрес сайта, применяя в файле robots.txt директиву Host.
                               Она не исключает ничего из индекса, а указывает, на какой домен надо ориентироваться для
                               данного сайта. Директива Host самый безопасный, но, к сожалению, ненадежный способ
                               сменить домен. Она имеет не обязательный характер, а рекомендательный, и поисковик может
                               и не принять ее во внимание. </p>

        <p class="description">Таким образом, нет универсального способа, чтобы склейка <a href="домен">доменов</a>
                               угодила всем поисковым машинам одновременно. Поэтому на практике необходимо &quot;удовлетворять&quot;
                               каждый поисковик по отдельности.</p>
