            Какая верстка лучше?
        </h4>

        <p class="description">
            Вёрстка представляет собой процесс формирования страниц какого-либо издания, будь то бумажный носитель либо
            Интернет-сайт, с использованием для этого текстовых и графических элементов. </p>

        <p class="description">Различают табличную и блочную вёрстку, причём сторонники того или иного вида постоянно
                               спорят между собой по поводу их эффективности и целесообразности.
                               Верстальщики таблицами включают их повсюду, нередко не только целые абзацы помещаются в
                               таблицы, но и отдельные предложения и даже некоторые слова. </p>

        <p class="description">Такое нагромождение таблиц не только мешает, но и раздражает многих пользователей.
                               Верстальщики блоками совершают другие ошибки. Использование для создания блоков различных
                               кодов, хаков, растяжек и прочих хитростей, позволяющих максимально уподобить блоки
                               таблицам, ухудшает дизайн самих блоков, которые при использовании другого браузера
                               расползаются в разные стороны, ломая при этом внешний вид всей страницы. </p>

        <p class="description">Кодирование блоками, безусловно, компактнее, но эффект зачастую получается совершенно
                               противоположным. Однако страница, свёрстанная с использованием блоков, скорее
                               отображается, тогда, как отображение таблицы происходит только после её полной
                               загрузки. </p>

        <p class="description">Безусловно, и тот и другой способ вёрстки имеет как свои преимущества, так и недостатки.
                               Поэтому нет смысла затевать спор о том, как вёрстка лучше – блочная или табличная? В
                               любом случае выбор зависит от личных предпочтений заказчика и дизайна конкретной
                               страницы. </p>
